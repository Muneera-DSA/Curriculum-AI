import React, { useState } from 'react';
import { X, Copy, Check, Download, Printer, FileText } from 'lucide-react';
import { CurriculumAIResponse } from '../types/curriculum';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  data: CurriculumAIResponse | null;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  data,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen || !data) return null;

  const generateMarkdown = () => {
    let md = `# Course Syllabus: ${data.course_overview.topic}\n\n`;
    md += `**Target Level:** ${data.course_overview.target_level}\n`;
    md += `**Estimated Duration:** ${data.course_overview.estimated_completion_time_weeks} Weeks\n\n`;
    md += `## Course Overview\n${data.course_overview.summary}\n\n---\n\n`;

    data.curriculum.forEach((mod) => {
      md += `## Module ${mod.module_number}: ${mod.module_title}\n\n`;
      md += `### Learning Objectives\n`;
      mod.learning_objectives.forEach((obj) => {
        md += `- ${obj}\n`;
      });
      md += `\n### Core Concepts\n`;
      md += `${mod.core_concepts.join(' · ')}\n\n`;

      md += `### Curated Primary Sources & Search Vectors\n\n`;

      md += `#### 1. Textbooks & PDFs\n`;
      mod.resources.textbooks_and_pdfs.forEach((b) => {
        md += `- **${b.title}** by ${b.author_or_institution} (${b.type})\n  - *Search vector:* \`${b.search_query}\`\n`;
      });

      md += `\n#### 2. Seminal Research Papers\n`;
      mod.resources.research_papers.forEach((p) => {
        md += `- **${p.title}** — ${p.authors} (${p.venue_or_journal})\n  - *Search vector:* \`${p.search_query}\`\n`;
      });

      md += `\n#### 3. Web Guides & Documentation\n`;
      mod.resources.web_content.forEach((w) => {
        md += `- **${w.platform_or_site}**: ${w.content_description}\n  - *Search vector:* \`${w.search_query}\`\n`;
      });

      md += `\n#### 4. Audio/Visual Media & Podcasts\n`;
      mod.resources.audio_visual_and_podcasts.forEach((m) => {
        md += `- **${m.title_or_channel}** (${m.media_type})\n  - *Search vector:* \`${m.search_query}\`\n`;
      });

      md += `\n### Practical Milestone Project\n`;
      md += `> ${mod.practical_milestone_project}\n\n---\n\n`;
    });

    md += `*Generated by CurriculumAI Academic Advisor*\n`;
    return md;
  };

  const markdownContent = generateMarkdown();

  const handleCopy = () => {
    navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${data.course_overview.topic.toLowerCase().replace(/[^a-z0-9]/g, '_')}_syllabus.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl max-w-3xl w-full max-h-[85vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between p-4 border-b border-slate-200 dark:border-slate-800 bg-slate-50 dark:bg-slate-950">
          <div className="flex items-center gap-2">
            <div className="p-1.5 rounded-lg bg-indigo-100 dark:bg-indigo-950 text-indigo-700 dark:text-indigo-400">
              <FileText className="w-4 h-4" />
            </div>
            <div>
              <h3 className="font-bold text-sm sm:text-base text-slate-900 dark:text-white">
                Export Academic Syllabus
              </h3>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Download formatted Markdown or generate print view
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-slate-300 dark:border-slate-700 hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-700 dark:text-slate-200 text-xs font-semibold transition-colors"
              title="Print syllabus"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>Print</span>
            </button>

            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold transition-all shadow-sm"
              title="Download .md file"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download .md</span>
            </button>

            <button
              onClick={onClose}
              className="p-1.5 rounded-lg hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-400 hover:text-slate-700 dark:hover:text-white transition-colors"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Preview Content */}
        <div className="flex-1 overflow-auto p-5 bg-slate-50/50 dark:bg-slate-950/50 font-mono text-xs text-slate-800 dark:text-slate-200 leading-relaxed">
          <pre className="whitespace-pre-wrap select-all">
            {markdownContent}
          </pre>
        </div>

        {/* Footer */}
        <div className="p-3 border-t border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 flex items-center justify-between text-xs text-slate-500">
          <span>Complete Markdown course syllabus with search vectors</span>
          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-100 hover:bg-slate-200 dark:bg-slate-800 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-200 font-semibold transition-colors"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-500" />
                <span>Copied to Clipboard</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Markdown</span>
              </>
            )}
          </button>
        </div>
      </div>
    </div>
  );
};
